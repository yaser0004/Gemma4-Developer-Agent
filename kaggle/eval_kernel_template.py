"""Kaggle GPU kernel: evaluate agent variants with the official harness and the real model.

Generated by kaggle/build_eval_kernel.py, which fills in VARIANTS_ZIP_B64, TASK_IDS and the
budgets. Mirrors the organizers' "Getting Started - Gemma 4 Developer Agent" notebook
(ryanholbrook/getting-started-gemma-4-developer-agent), which runs on the NvidiaL4 machine
shape with internet disabled:

1. install every wheel from the organizers' wheelhouse with --no-deps (offline),
2. start vLLM through adk_submission.VllmServer with the scorer's parsers,
3. optionally verify each task's gold patch through the same path (positive control: shows the
   Kaggle grading environment can resolve the task at all),
4. run swegemma's Evaluator (subprocess sandbox) for each variant and task,
5. write per-variant results (patches, exit codes, test output tails) under /kaggle/working.

T4 machines cannot run this: vLLM 0.19.1 forces its Triton attention backend for Gemma 4
(head_dim 256/512), and the head_dim-512 kernel needs 96 KB of shared memory (T4: 64 KB).
"""

import asyncio
import base64
import concurrent.futures
import glob
import importlib
import io
import json
import os
import shutil
import subprocess
import sys
import time
import zipfile
from pathlib import Path

VARIANTS_ZIP_B64 = "__VARIANTS_ZIP_B64__"
TASK_IDS = __TASK_IDS__
MAX_TIME_MINUTES = __MAX_TIME_MINUTES__
MAX_TOOL_CALLS = __MAX_TOOL_CALLS__
MAX_TURNS = __MAX_TURNS__
GOLD_CONTROL = __GOLD_CONTROL__
TIMEOUT_SECONDS = 180
TARGET_MODEL_NAME = "gemma-4-31b-it-qat-w4a16-ct"
WORK = Path("/kaggle/working")
DATA_DIR = Path("/kaggle/input/competitions/gemma-4-developer-agent")
WHEELHOUSE_DIR = Path("/kaggle/input/datasets/metric/gemma-4-developer-agent-wheelhouse")
MODEL_PATH = Path("/kaggle/input/models/google/gemma-4/other/gemma-4-31b-it-qat-w4a16-ct/2")
LOG = WORK / "eval_kernel.log"

os.environ.update({
    "LITELLM_LOCAL_MODEL_COST_MAP": "True",
    "TRANSFORMERS_NO_TF": "1",
    "VLLM_WORKER_MULTIPROC_METHOD": "spawn",
    "VLLM_MEMORY_PROFILER_ESTIMATE_CUDAGRAPHS": "1",
    "VLLM_ENGINE_READY_TIMEOUT_S": "1200",
    "VLLM_NO_USAGE_STATS": "1",
    "OTEL_SDK_DISABLED": "true",
    "PYTORCH_CUDA_ALLOC_CONF": "expandable_segments:True",
})


def log(msg: str) -> None:
    line = f"[{time.strftime('%H:%M:%S')}] {msg}"
    print(line, flush=True)
    with LOG.open("a") as fh:
        fh.write(line + "\n")


def install() -> None:
    """Organizers' recipe: restore stripped '+cu128' wheel names, install all with --no-deps."""
    for pattern in ("/usr/local/lib/python*/dist-packages/*cutlass*.pth", "/usr/local/lib/python*/site-packages/*cutlass*.pth"):
        for pth in glob.glob(pattern):
            try:
                os.unlink(pth)
            except OSError:
                pass
    tmp = Path("/tmp/wheelhouse")
    tmp.mkdir(parents=True, exist_ok=True)
    for w in WHEELHOUSE_DIR.glob("*.whl"):
        if "cutlass" in w.name.lower():
            continue
        name = w.name.replace("cu128", "+cu128") if ("cu128" in w.name and "+" not in w.name) else w.name
        if not (tmp / name).exists():
            os.symlink(w, tmp / name)
    wheels = sorted(str(w) for w in tmp.glob("*.whl"))
    log(f"installing {len(wheels)} wheels")
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps", "--force-reinstall", *wheels], check=True)
    importlib.invalidate_caches()


def run_sync(fn):
    """Run an async callable to completion, also when an event loop is already running."""
    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        loop = None
    if loop is not None and loop.is_running():
        with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
            return pool.submit(lambda: asyncio.run(fn())).result()
    return asyncio.run(fn())


def main() -> None:
    WORK.mkdir(parents=True, exist_ok=True)
    install()
    out = subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv,noheader"], capture_output=True, text=True)
    log("GPUs:\n" + out.stdout.strip())

    import litellm
    import torch
    from adk_submission import VllmConfig, VllmServer, discover_adapters
    from google.adk.agents.context_cache_config import ContextCacheConfig
    from google.adk.apps._configs import EventsCompactionConfig
    from swegemma.config import ALLOWED_ADAPTER_EXTENSIONS, EvalConfig, build_submission_limits
    from swegemma.evaluate import Evaluator
    from swegemma.models import load_tasks

    litellm.drop_params = True
    variants_root = WORK / "variants"
    with zipfile.ZipFile(io.BytesIO(base64.b64decode(VARIANTS_ZIP_B64))) as zf:
        zf.extractall(variants_root)
    variants = sorted(p for p in variants_root.iterdir() if p.is_dir())

    gpu_count = torch.cuda.device_count()
    tp = 4 if gpu_count >= 4 else (2 if gpu_count >= 2 else 1)
    cfg = VllmConfig(
        model=str(MODEL_PATH), port=8000, host="127.0.0.1",
        tool_call_parser="gemma4", reasoning_parser="gemma4",
        default_chat_template_kwargs={"enable_thinking": True},
        max_model_len=32768,
        dtype="bfloat16" if torch.cuda.is_bf16_supported() else "auto",
        gpu_memory_utilization=0.90, enable_auto_tool_choice=True,
        enable_lora=False, tensor_parallel_size=tp, startup_timeout=60 * 20,
    )
    server = VllmServer(cfg, adapter_manifest=discover_adapters(str(variants[0]), adapter_extensions=ALLOWED_ADAPTER_EXTENSIONS))
    t0 = time.time()
    server.start()
    log(f"vLLM ready in {time.time() - t0:.0f}s (tp={tp}) at {server.base_url}")
    models = server.create_model_registry(aliases=[TARGET_MODEL_NAME], model_prefix="openai/", api_key="EMPTY")

    all_tasks = {t.instance_id: t for t in load_tasks(DATA_DIR / "tasks.jsonl")}
    tasks = [all_tasks[i] for i in TASK_IDS if i in all_tasks]
    limits, gen_constraints = build_submission_limits()
    summary = {}
    if GOLD_CONTROL:
        from swegemma.deduplication import resolve_task_snapshot_paths
        from swegemma.harness.verification import verify_task
        gold_eval = Evaluator(EvalConfig(
            tasks_path=DATA_DIR / "tasks.jsonl", snapshots_dir=DATA_DIR / "snapshots",
            results_dir=WORK / "results" / "_gold", submission_dir=variants[0], models=models,
            sandbox="subprocess", timeout_seconds=TIMEOUT_SECONDS, limits=limits,
            generation_constraints=gen_constraints, wheels_dir=DATA_DIR / "wheels", verbose=False))
        gold_rows = []
        for task in tasks:
            snap, base, patch_path = resolve_task_snapshot_paths(gold_eval.config.snapshots_dir, task.instance_id, task.repo)
            try:
                res = run_sync(lambda: verify_task(gold_eval.docker, gold_eval.config, task, snap, base_snapshot_path=base,
                                                   patch_path=patch_path, agent_patch=task.patch))
                row = {"id": task.instance_id, "resolved": bool(res.resolved), "exit": res.test_exit_code}
            except Exception as exc:  # noqa: BLE001
                row = {"id": task.instance_id, "resolved": False, "error": f"{type(exc).__name__}: {exc}"[:300]}
            gold_rows.append(row)
            log(f"gold {json.dumps(row)}")
        summary["_gold"] = {"resolved": sum(r["resolved"] for r in gold_rows), "total": len(gold_rows), "tasks": gold_rows}
    for variant in variants:
        cfg_eval = EvalConfig(
            tasks_path=DATA_DIR / "tasks.jsonl", snapshots_dir=DATA_DIR / "snapshots",
            results_dir=WORK / "results" / variant.name, submission_dir=variant, models=models,
            sandbox="subprocess", timeout_seconds=TIMEOUT_SECONDS, max_time_minutes=MAX_TIME_MINUTES,
            max_tool_calls=MAX_TOOL_CALLS, max_turns=MAX_TURNS,
            limits=limits, generation_constraints=gen_constraints, adapter_manifest=None,
            context_cache_config=ContextCacheConfig(min_tokens=2048, ttl_seconds=1800, cache_intervals=10),
            events_compaction_config=EventsCompactionConfig(compaction_interval=15, overlap_size=2,
                                                            token_threshold=14336, event_retention_size=5),
            graph_dir=str(DATA_DIR / "graphs"), embeddings_dir=str(DATA_DIR / "embeddings"),
            wheels_dir=DATA_DIR / "wheels", verbose=False,
        )
        evaluator = Evaluator(cfg_eval)
        rows = []
        for idx, task in enumerate(tasks, start=1):
            t0 = time.time()
            try:
                r = run_sync(lambda: evaluator.evaluate_task(task=task, task_index=idx, total_tasks=len(tasks)))
                row = {"id": task.instance_id, "resolved": bool(r.resolved), "tool_calls": r.tool_calls,
                       "patch_chars": len(r.agent_patch or ""), "exit": r.test_exit_code,
                       "seconds": round(r.duration_seconds, 1), "error": (getattr(r, "error", None) or "")[:300]}
                out_dir = WORK / "results" / variant.name / "artifacts"
                out_dir.mkdir(parents=True, exist_ok=True)
                (out_dir / f"{task.instance_id}.patch").write_text(r.agent_patch or "")
                (out_dir / f"{task.instance_id}.test.txt").write_text((getattr(r, "test_output", "") or "")[-6000:])
            except Exception as exc:  # noqa: BLE001 - keep evaluating the remaining tasks
                row = {"id": task.instance_id, "resolved": False, "error": f"{type(exc).__name__}: {exc}"[:300],
                       "seconds": round(time.time() - t0, 1)}
            rows.append(row)
            log(f"{variant.name} {json.dumps(row)}")
        summary[variant.name] = {"resolved": sum(r["resolved"] for r in rows), "total": len(rows), "tasks": rows}
        (WORK / "summary_all.json").write_text(json.dumps(summary, indent=2))
    log("summary: " + json.dumps({k: f"{v['resolved']}/{v['total']}" for k, v in summary.items()}))
    server.stop()
    shutil.rmtree(variants_root, ignore_errors=True)


if __name__ == "__main__":
    main()
