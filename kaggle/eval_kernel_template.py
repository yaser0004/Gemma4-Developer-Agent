"""Kaggle GPU kernel: evaluate agent variants with the official harness and the real model.

Generated by kaggle/build_eval_kernel.py, which fills in VARIANTS_ZIP_B64, TASK_IDS and
settings. Runs on a Kaggle GPU notebook (2x T4) with the competition data, the organizers'
wheelhouse dataset and the gemma-4-31b-it-qat-w4a16-ct model attached:

1. install vLLM 0.19.1 and the harness packages from the wheelhouse,
2. serve the QAT model with vLLM on localhost (the model never leaves the notebook),
3. run `swegemma eval --sandbox subprocess` (no Docker on Kaggle) for each variant,
4. write results to /kaggle/working/results/<variant>/ for `kaggle kernels output`.

Differences from the scorer: 2x T4 instead of 4x L4 (fp16, slower, less KV cache), the
subprocess sandbox instead of Docker, and per-task time limits scaled for T4 speed.
"""

import base64
import glob
import io
import json
import os
import shutil
import subprocess
import sys
import time
import urllib.request
import zipfile
from pathlib import Path

VARIANTS_ZIP_B64 = "__VARIANTS_ZIP_B64__"
TASK_IDS = __TASK_IDS__
MAX_TIME_MINUTES = __MAX_TIME_MINUTES__
MAX_TOOL_CALLS = __MAX_TOOL_CALLS__
MAX_TURNS = __MAX_TURNS__
SERVED_NAME = "gemma-4-31b-it-qat-w4a16-ct"
WORK = Path("/kaggle/working")
LOG = WORK / "eval_kernel.log"


def log(msg: str) -> None:
    line = f"[{time.strftime('%H:%M:%S')}] {msg}"
    print(line, flush=True)
    with LOG.open("a") as fh:
        fh.write(line + "\n")


def find_one(patterns: list[str], what: str) -> Path:
    for pattern in patterns:
        hits = sorted(glob.glob(pattern, recursive=True))
        if hits:
            return Path(hits[0])
    raise SystemExit(f"could not find {what}; tried {patterns}")


def sh(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    log("$ " + " ".join(cmd)[:300])
    return subprocess.run(cmd, check=False, **kw)


def install() -> Path:
    wheelhouse = find_one(["/kaggle/input/**/vllm-0.19.1-*.whl"], "organizers' wheelhouse (vllm wheel)").parent
    wheels = sorted(str(p) for p in wheelhouse.glob("*.whl"))
    harness = [w for w in wheels if Path(w).name.startswith(("swegemma-", "adk_submission-", "adk_eval_core-"))]
    others = [w for w in wheels if w not in harness]
    # Internet is on: pip resolves anything the wheelhouse does not carry (e.g. torch).
    sh([sys.executable, "-m", "pip", "install", "-q", "--find-links", str(wheelhouse), *others])
    sh([sys.executable, "-m", "pip", "install", "-q", "--no-deps", *harness])
    sh([sys.executable, "-m", "pip", "install", "-q", "docker", "networkx", "cachetools", "python-dotenv", "rich"])
    return wheelhouse


def start_vllm(model_dir: Path) -> subprocess.Popen:
    for max_len in (32768, 24576, 16384):
        cmd = [sys.executable, "-m", "vllm.entrypoints.openai.api_server", "--model", str(model_dir),
               "--served-model-name", SERVED_NAME, "--host", "127.0.0.1", "--port", "8000",
               "--tensor-parallel-size", "2", "--dtype", "half", "--max-model-len", str(max_len),
               "--gpu-memory-utilization", "0.92", "--enable-auto-tool-choice",
               "--tool-call-parser", "gemma4", "--reasoning-parser", "gemma4",
               "--limit-mm-per-prompt", json.dumps({"image": 0, "audio": 0})]
        log(f"starting vLLM with max_model_len={max_len}")
        out = (WORK / f"vllm_{max_len}.log").open("w")
        proc = subprocess.Popen(cmd, stdout=out, stderr=subprocess.STDOUT)
        deadline = time.time() + 45 * 60
        while time.time() < deadline and proc.poll() is None:
            try:
                with urllib.request.urlopen("http://127.0.0.1:8000/v1/models", timeout=5) as r:
                    if r.status == 200:
                        log(f"vLLM ready (max_model_len={max_len})")
                        return proc
            except OSError:
                time.sleep(15)
        log(f"vLLM failed at max_model_len={max_len} (exit={proc.poll()}); see vllm_{max_len}.log")
        proc.kill()
    raise SystemExit("vLLM could not start")


def smoke_test() -> None:
    body = json.dumps({"model": SERVED_NAME, "max_tokens": 64,
                       "messages": [{"role": "user", "content": "Reply with exactly: READY"}]}).encode()
    req = urllib.request.Request("http://127.0.0.1:8000/v1/chat/completions", data=body,
                                 headers={"Content-Type": "application/json"})
    t = time.time()
    with urllib.request.urlopen(req, timeout=600) as r:
        reply = json.load(r)
    log(f"smoke test {time.time() - t:.1f}s: {json.dumps(reply)[:400]}")


def main() -> None:
    WORK.mkdir(parents=True, exist_ok=True)
    install()
    model_dir = find_one(["/kaggle/input/**/gemma-4-31b-it-qat-w4a16-ct/**/config.json"], "QAT model").parent
    data_dir = find_one(["/kaggle/input/**/gemma-4-developer-agent/tasks.jsonl",
                         "/kaggle/input/**/tasks.jsonl"], "competition data").parent
    server = start_vllm(model_dir)
    smoke_test()

    variants_root = WORK / "variants"
    with zipfile.ZipFile(io.BytesIO(base64.b64decode(VARIANTS_ZIP_B64))) as zf:
        zf.extractall(variants_root)
    models_yaml = WORK / "models_local.yaml"
    models_yaml.write_text(f"models:\n  {SERVED_NAME}:\n    path: openai/{SERVED_NAME}\n"
                           "    api_base: http://127.0.0.1:8000/v1\n")
    os.environ.setdefault("OPENAI_API_KEY", "EMPTY")

    summary = {}
    for variant in sorted(p.name for p in variants_root.iterdir() if p.is_dir()):
        out = WORK / "results" / variant
        res = sh([sys.executable, "-m", "swegemma.cli", "eval",
                  "--tasks", str(data_dir / "tasks.jsonl"), "--snapshots-dir", str(data_dir / "snapshots"),
                  "--results-dir", str(out), "--submission-dir", str(variants_root / variant),
                  "--sandbox", "subprocess", "--models-yaml", str(models_yaml),
                  "--max-time-minutes", str(MAX_TIME_MINUTES), "--max-tool-calls", str(MAX_TOOL_CALLS),
                  "--max-turns", str(MAX_TURNS), "--display", "quiet", "--task-ids", *TASK_IDS],
                 stdout=(WORK / f"eval_{variant}.log").open("w"), stderr=subprocess.STDOUT)
        summary_file = out / "summary.json"
        summary[variant] = json.loads(summary_file.read_text()) if summary_file.exists() else {"exit": res.returncode}
        log(f"{variant}: {json.dumps(summary[variant])[:300]}")
    (WORK / "summary_all.json").write_text(json.dumps(summary, indent=2))
    server.terminate()
    shutil.rmtree(variants_root, ignore_errors=True)


if __name__ == "__main__":
    main()
