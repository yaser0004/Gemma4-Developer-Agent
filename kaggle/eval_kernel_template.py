"""Kaggle GPU kernel: evaluate agent variants with the official harness and the real model.

Generated by kaggle/build_eval_kernel.py, which fills in the placeholders below. It follows the
organizers' "Getting Started - Gemma 4 Developer Agent" notebook (NvidiaL4 = 4x L4, internet off):

1. install every wheel of the organizers' wheelhouse with --no-deps (offline),
2. start vLLM through adk_submission.VllmServer with the scorer's flags, once for the model
   that all variants share,
3. run swegemma's Evaluator.run (subprocess sandbox, the same Phase 1 + Phase 2 as the scorer)
   for each variant on the task list, with the variant's own eval_config.yaml budgets,
4. sample vLLM's /metrics in the background (concurrent requests, prefix-cache hits, tokens),
5. leave everything under /kaggle/working: per-variant results dirs (summary.json,
   task_results.jsonl, patches/, traces/, test_outputs/), vllm.log, metrics.jsonl, summary_all.json.

T4 machines cannot run this: vLLM 0.19.1 forces its Triton attention backend for Gemma 4
(head_dim 256/512), and the head_dim-512 kernel needs 96 KB of shared memory (T4: 64 KB).
"""

