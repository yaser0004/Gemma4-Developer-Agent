def log(msg: str) -> None:
    line = f"[{time.strftime('%H:%M:%S')}] {msg}"
    print(line, flush=True)
    with LOG.open("a") as fh:
        fh.write(line + "\n")


def install() -> None:
    """Organizers' recipe: restore stripped '+cu128' wheel names, install all with --no-deps."""
    for pattern in ("/usr/local/lib/python*/dist-packages/*cutlass*.pth", "/usr/local/lib/python*/site-packages/*cutlass*.pth"):
        for pth in glob.glob(pattern):
            try:
                os.unlink(pth)
            except OSError:
                pass
    tmp = Path("/tmp/wheelhouse")
    tmp.mkdir(parents=True, exist_ok=True)
    for w in WHEELHOUSE_DIR.glob("*.whl"):
        if "cutlass" in w.name.lower():
            continue
        name = w.name.replace("cu128", "+cu128") if ("cu128" in w.name and "+" not in w.name) else w.name
        if not (tmp / name).exists():
            os.symlink(w, tmp / name)
    wheels = sorted(str(w) for w in tmp.glob("*.whl"))
    log(f"python {sys.version.split()[0]}; installing {len(wheels)} wheels")
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps", "--force-reinstall", *wheels], check=True)
    importlib.invalidate_caches()


def run_sync(coro_fn):
    """Run an async callable to completion, also when an event loop is already running."""
    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        loop = None
    if loop is not None and loop.is_running():
        with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
            return pool.submit(lambda: asyncio.run(coro_fn())).result()
    return asyncio.run(coro_fn())


def sample_metrics(stop: threading.Event) -> None:
    """Every 5 s append the vLLM gauges that tell us whether parallel requests really overlap."""
    wanted = ("vllm:num_requests_running", "vllm:num_requests_waiting", "vllm:prefix_cache_queries_total",
              "vllm:prefix_cache_hits_total", "vllm:prompt_tokens_total", "vllm:generation_tokens_total",
              "vllm:gpu_cache_usage_perc", "vllm:kv_cache_usage_perc")
    with (WORK / "metrics.jsonl").open("a") as out:
        while not stop.wait(5):
            try:
                text = urllib.request.urlopen("http://127.0.0.1:8000/metrics", timeout=3).read().decode()
            except Exception:  # noqa: BLE001 - metrics are best effort
                continue
            row = {"t": round(time.time(), 1)}
            for line in text.splitlines():
                if line.startswith(wanted):
                    name, _, value = line.rpartition(" ")
                    row[re.sub(r"\{.*\}", "", name)] = float(value)
            out.write(json.dumps(row) + "\n")
            out.flush()


def main() -> None:
    WORK.mkdir(parents=True, exist_ok=True)
    install()
    out = subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total", "--format=csv,noheader"], capture_output=True, text=True)
    log("GPUs:\n" + out.stdout.strip())

    import litellm
    import torch
    import yaml
    from adk_submission import VllmConfig, VllmServer, discover_adapters
    from adk_submission.discovery import discover_declared_models
    from google.adk.agents.context_cache_config import ContextCacheConfig
    from google.adk.apps._configs import EventsCompactionConfig
    from swegemma.config import ALLOWED_ADAPTER_EXTENSIONS, EvalConfig, build_submission_limits
    from swegemma.evaluate import Evaluator

    litellm.drop_params = True
    variants_root = WORK / "variants"
    with zipfile.ZipFile(io.BytesIO(base64.b64decode(VARIANTS_ZIP_B64))) as zf:
        zf.extractall(variants_root)
    variants = sorted(p for p in variants_root.iterdir() if p.is_dir())
    for variant in variants:
        declared = discover_declared_models(variant)
        assert declared == {MODEL_NAME}, f"{variant.name} declares {sorted(declared)}, kernel serves {MODEL_NAME}"

    gpu_count = torch.cuda.device_count()
    tp = 4 if gpu_count >= 4 else (2 if gpu_count >= 2 else 1)
    adapters = discover_adapters(str(variants[0]), adapter_extensions=ALLOWED_ADAPTER_EXTENSIONS)
    adapter_map = getattr(adapters, "adapters", None) or {}
    ranks = [r for info in adapter_map.values() if (r := getattr(info, "rank", None)) is not None and r > 0]
    cfg = VllmConfig(
        model=str(MODEL_PATH), port=8000, host="127.0.0.1",
        tool_call_parser="gemma4", reasoning_parser="gemma4",
        max_model_len=32768,
        dtype="bfloat16" if torch.cuda.is_bf16_supported() else "auto",
        gpu_memory_utilization=0.90, enable_auto_tool_choice=True,
        enable_lora=bool(adapter_map), max_loras=max(1, len(adapter_map)),
        max_lora_rank=max(ranks) if ranks else 128, scheduler_reserve_full_isl=False,
        tensor_parallel_size=tp, startup_timeout=60 * 20,
        extra_args=MODEL_VLLM_EXTRA_ARGS.get(MODEL_NAME, ()),
    )
    server = VllmServer(cfg, adapter_manifest=adapters)
    t0 = time.time()
    server.start()
    log(f"vLLM ready in {time.time() - t0:.0f}s (tp={tp}, model={MODEL_NAME}) at {server.base_url}")
    models = server.create_model_registry(aliases=[MODEL_NAME], model_prefix="openai/", api_key="EMPTY")
    stop = threading.Event()
    threading.Thread(target=sample_metrics, args=(stop,), daemon=True).start()

    limits, gen_constraints = build_submission_limits()
    summary = {}
    for variant in variants:
        raw = {}
        for name in ("eval_config.yaml", "eval_config.yml"):
            if (variant / name).is_file():
                raw = yaml.safe_load((variant / name).read_text(encoding="utf-8")) or {}
                break
        ev = raw.get("evaluation", raw)
        turns = ev.get("max_turns", ev.get("max_llm_calls"))
        results_dir = WORK / "results" / variant.name
        cfg_eval = EvalConfig(
            tasks_path=DATA_DIR / "tasks.jsonl", snapshots_dir=DATA_DIR / "snapshots",
            results_dir=results_dir, submission_dir=variant, models=models, sandbox="subprocess",
            timeout_seconds=int(ev.get("timeout_seconds", 300)),
            verification_timeout_seconds=300,
            max_time_minutes=float(ev.get("max_time_minutes", 60.0)) * TIME_SCALE,
            max_tool_calls=int(ev.get("max_tool_calls", 100)),
            max_turns=int(turns) if turns is not None else None,
            task_ids=TASK_IDS, concurrency=CONCURRENCY, display_mode="quiet",
            limits=limits, generation_constraints=gen_constraints, adapter_manifest=adapters,
            context_cache_config=ContextCacheConfig(min_tokens=2048, ttl_seconds=1800, cache_intervals=10),
            events_compaction_config=EventsCompactionConfig(compaction_interval=15, overlap_size=2,
                                                            token_threshold=14336, event_retention_size=5),
            graph_dir=str(DATA_DIR / "graphs"), embeddings_dir=str(DATA_DIR / "embeddings"),
            wheels_dir=DATA_DIR / "wheels", verbose=False,
        )
        t_arm = time.time()
        log(f"arm {variant.name}: {len(TASK_IDS)} tasks, concurrency {CONCURRENCY}, time scale {TIME_SCALE}")
        result = run_sync(Evaluator(cfg_eval).run)
        rows = [{"id": r.instance_id, "resolved": bool(r.resolved), "tool_calls": r.tool_calls,
                 "patch_chars": len(r.agent_patch or ""), "exit": r.test_exit_code,
                 "seconds": round(getattr(r, "duration_seconds", 0) or 0, 1),
                 "error": (getattr(r, "error_message", None) or "")[:300]} for r in result.task_results]
        summary[variant.name] = {"resolved": sum(r["resolved"] for r in rows), "total": len(rows),
                                 "wall_seconds": round(time.time() - t_arm), "tasks": rows}
        (WORK / "summary_all.json").write_text(json.dumps(summary, indent=2))
        log(f"arm {variant.name}: {summary[variant.name]['resolved']}/{len(rows)} in {summary[variant.name]['wall_seconds']}s")
    stop.set()
    server.stop()
    shutil.copy(server.log_path, WORK / "vllm.log")
    shutil.rmtree(variants_root, ignore_errors=True)


if __name__ == "__main__":
    main()
